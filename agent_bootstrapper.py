def public_ip():
    """Best-effort local address reported with the heartbeat."""
    try:
        sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        try:
            sock.connect(("8.8.8.8", 80))
            return sock.getsockname()[0]
        finally:
            sock.close()
    except OSError:
        try:
            return socket.gethostbyname(socket.gethostname())
        except OSError:
            return "127.0.0.1"


def send_heartbeat():
    """Report liveness so the agent stays 'online' in the command center."""
    import requests
    try:
        requests.post(
            HEARTBEAT_ENDPOINT,
            headers=api_headers(),
            json={"service_id": SERVICE_ID, "ip_address": public_ip()},
            timeout=15,
        )
        return True
    except Exception:
        return False


